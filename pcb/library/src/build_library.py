#!/usr/bin/env python3
"""Builds the JR component library from jr_parts.py, jr_symbols.py and jr_footprints.py.

    /usr/bin/python3 pcb/library/src/build_library.py [out dir]      (default: pcb/library)

Writes:
    JR.lbr          EAGLE library: Altium 19 File > Import Wizard > EAGLE turns it into JR.SchLib + JR.PcbLib
    JR.pretty/      KiCad footprints (used to build and check the boards here)
    JR.kicad_sym    KiCad symbols: one base symbol per drawing, one derived symbol per part with its parameters
    JR_parts.csv    the part table: name, symbol, footprint, parameters
(JR_preview.pdf, one page per part, is drawn afterwards by preview.py.)

Needs KiCad 7's Python module (pcbnew), run with /usr/bin/python3.
"""
import csv
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)
import pcbnew  # noqa: E402

import eagle  # noqa: E402
import jr_footprints  # noqa: E402
from jr_parts import PARTS, part  # noqa: E402
from jr_symbols import all_symbols  # noqa: E402

LIB = "JR"
DESC = ("JR component library (Jase's shared parts for the macropad, the Gameball carrier and later boards). "
        "Generated by pcb/library/src/build_library.py; edit the generator, not the library.")


def q(s):
    return '"' + str(s).replace("\\", "\\\\").replace('"', '\\"') + '"'


def kicad_sym(symbols, out):
    """KiCad 7 symbol library: base drawings, then one derived ("extends") symbol per part."""
    n = eagle.f
    eff = lambda size=1.27, just=None, hide=False: (f'(effects (font (size {size} {size}))'
                                                   + (f" (justify {just})" if just else "") + (" hide" if hide else "") + ")")
    lines = ['(kicad_symbol_lib (version 20220914) (generator jr_library)']
    for s in symbols.values():
        opts = ""
        if s.hide_pin_numbers: opts += " (pin_numbers hide)"
        if s.hide_pin_names: opts += " (pin_names (offset 0.254) hide)"
        else: opts += " (pin_names (offset 0.762))"
        lines.append(f'  (symbol {q(s.name)}{opts} (in_bom yes) (on_board yes)')
        rx, ry, rj = s.ref_at; vx, vy, vj = s.val_at
        lines.append(f'    (property "Reference" {q(s.prefix)} (at {n(rx)} {n(ry)} 0) {eff(1.27, rj if rj != "center" else None)})')
        lines.append(f'    (property "Value" {q(s.name)} (at {n(vx)} {n(vy)} 0) {eff(1.27, vj if vj != "center" else None)})')
        lines.append(f'    (property "Footprint" "" (at 0 0 0) {eff(hide=True)})')
        lines.append(f'    (property "Datasheet" "" (at 0 0 0) {eff(hide=True)})')
        lines.append(f'    (property "ki_description" {q(s.desc)} (at 0 0 0) {eff(hide=True)})')
        lines.append(f'    (symbol {q(s.name + "_0_1")}')
        st = '(stroke (width 0.254) (type default))'
        for it in s.items:
            k = it[0]
            if k == "rect":
                _, x0, y0, x1, y1, filled = it
                lines.append(f'      (rectangle (start {n(x0)} {n(y0)}) (end {n(x1)} {n(y1)}) {st} (fill (type {"outline" if filled else "background" if (x1-x0)*(y1-y0) > 20 else "none"})))')
            elif k == "poly":
                _, pts, filled = it
                xy = " ".join(f"(xy {n(x)} {n(y)})" for x, y in pts)
                lines.append(f'      (polyline (pts {xy}) {st} (fill (type {"outline" if filled else "none"})))')
            elif k == "circle":
                _, x, y, r, filled = it
                lines.append(f'      (circle (center {n(x)} {n(y)}) (radius {n(r)}) {st} (fill (type {"outline" if filled else "none"})))')
            elif k == "arc":
                _, s0, m0, e0 = it
                lines.append(f'      (arc (start {n(s0[0])} {n(s0[1])}) (mid {n(m0[0])} {n(m0[1])}) (end {n(e0[0])} {n(e0[1])}) {st} (fill (type none)))')
            elif k == "text":
                _, txt, x, y, size = it
                lines.append(f'      (text {q(txt)} (at {n(x)} {n(y)} 0) {eff(size)})')
        lines.append('    )')
        lines.append(f'    (symbol {q(s.name + "_1_1")}')
        for num, name, x, y, d, length in s.pins:
            lines.append(f'      (pin passive line (at {n(x)} {n(y)} {d}) (length {n(length)}) '
                         f'(name {q(name)} {eff()}) (number {q(num)} {eff()}))')
        lines.append('    )')
        lines.append('  )')
    for name in PARTS:
        p = part(name)
        s = symbols[p["symbol"]]
        rx, ry, rj = s.ref_at; vx, vy, vj = s.val_at
        lines.append(f'  (symbol {q(name)} (extends {q(p["symbol"])})')
        props = [("Reference", s.prefix, rx, ry, False), ("Value", p["value"], vx, vy, False),
                 ("Footprint", f'{LIB}:{p["footprint"]}', 0, 0, True), ("Datasheet", "", 0, 0, True),
                 ("Description", p["description"], 0, 0, True), ("Manufacturer", p["manufacturer"], 0, 0, True),
                 ("Manufacturer Part Number", p["mpn"], 0, 0, True), ("LCSC", p["lcsc"], 0, 0, True),
                 ("ki_description", p["description"], 0, 0, True)]
        for k, v, x, y, hide in props:
            lines.append(f'    (property {q(k)} {q(v)} (at {n(x)} {n(y)} 0) {eff(hide=hide)})')
        lines.append('  )')
    lines.append(')')
    open(out, "w").write("\n".join(lines) + "\n")


def main(out):
    os.makedirs(out, exist_ok=True)
    pretty = os.path.join(out, f"{LIB}.pretty")
    if os.path.isdir(pretty):
        for fn in os.listdir(pretty):
            os.remove(os.path.join(pretty, fn))
    jr_footprints.build(pretty)
    symbols = all_symbols()

    used_fps = sorted({part(n)["footprint"] for n in PARTS})
    have = sorted(fn[:-10] for fn in os.listdir(pretty) if fn.endswith(".kicad_mod"))
    assert set(used_fps) <= set(have), set(used_fps) - set(have)
    fps = {n: pcbnew.FootprintLoad(pretty, n) for n in have}
    packages = [eagle.package_xml(fps[n], n) for n in have]
    used_syms = sorted({part(n)["symbol"] for n in PARTS})
    assert set(used_syms) <= set(symbols), set(used_syms) - set(symbols)
    sym_xml = [eagle.symbol_xml(symbols[n]) for n in sorted(symbols)]
    devs = []
    for name in PARTS:
        p = part(name)
        devs.append(eagle.deviceset_xml(p, symbols[p["symbol"]], eagle.pad_names(fps[p["footprint"]])))
    lib = eagle.library_xml(LIB, packages, sym_xml, devs, DESC)
    open(os.path.join(out, f"{LIB}.lbr"), "w").write(
        eagle.HEAD + eagle.layers_xml() + "\n<library>\n" + lib[lib.index("<description>"):lib.rindex("</library>")]
        + "</library>\n" + eagle.TAIL)
    kicad_sym(symbols, os.path.join(out, f"{LIB}.kicad_sym"))
    with open(os.path.join(out, f"{LIB}_parts.csv"), "w", newline="") as fh:
        w = csv.writer(fh)
        w.writerow(["Name", "Designator", "Symbol", "Footprint", "Value (Comment)", "Description", "Manufacturer",
                    "Manufacturer Part Number", "LCSC", "Used on"])
        for name in PARTS:
            p = part(name)
            w.writerow([name, symbols[p["symbol"]].prefix + "?", p["symbol"], p["footprint"], p["value"],
                        p["description"], p["manufacturer"], p["mpn"], p["lcsc"], p["used"]])
    print(f"{LIB}: {len(PARTS)} parts, {len(used_syms)} symbols, {len(have)} footprints -> {out}")


if __name__ == "__main__":
    main(sys.argv[1] if len(sys.argv) > 1 else os.path.dirname(HERE))
